// sfntTableMap returns the tables of the single font in an sfnt file.
func sfntTableMap(tb testing.TB, path string) map[string][]byte {
	tb.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		tb.Fatal(err)
	}
	n := int(binary.BigEndian.Uint16(data[4:]))
	tables := make(map[string][]byte, n)
	for i := range n {
		rec := data[12+16*i:]
		off := binary.BigEndian.Uint32(rec[8:])
		length := binary.BigEndian.Uint32(rec[12:])
		tables[string(rec[:4])] = data[off : off+length]
	}
	return tables
}

func lookup(tables map[string][]byte) func(string) []byte {
	return func(tag string) []byte { return tables[tag] }
}

func testFont(tb testing.TB, name string) *Font {
	tb.Helper()
	font, err := NewFont(lookup(sfntTableMap(tb, filepath.Join("..", "..", "testdata", name))))
	if err != nil {
		tb.Fatal(err)
	}
	return font
}

// dumpOutlines writes every glyph's hinted outline in the format testdata/ftdump.py writes FreeType's.
func dumpOutlines(tb testing.TB, font *Font, ppem float32, target Target) []byte {
	tb.Helper()
	in, err := font.NewInstance(ppem, target)
	if err != nil {
		tb.Fatalf("ppem %v: %v", ppem, err)
	}
	var buf bytes.Buffer
	var o Outline
	for gid := range font.numGlyphs {
		if !in.Outline(uint16(gid), &o) {
			fmt.Fprintf(&buf, "%d error\n", gid)
			continue
		}
		fmt.Fprintf(&buf, "%d %d %d:", gid, len(o.Points), len(o.ContourEnds))
		for i, p := range o.Points {
			on := 0
			if o.OnCurve[i] {
				on = 1
			}
			fmt.Fprintf(&buf, " %d,%d,%d", p.X, p.Y, on)
		}
		buf.WriteByte('\n')
	}
	return buf.Bytes()
}

func targetNamed(name string) Target {
	if name == "lcd" {
		return TargetLCD
	}
	return TargetNormal
}

// TestMatchesFreeType requires every glyph's hinted outline to be the one FreeType produces, coordinate for coordinate.
// The reference is a checksum per font, size and target, regenerated by testdata/gensums.sh.
func TestMatchesFreeType(t *testing.T) {
	sums, err := os.ReadFile(filepath.Join("testdata", "freetype.sums"))
	if err != nil {
		t.Fatal(err)
	}
	fonts := map[string]*Font{
		"Roboto-Regular.ttf":    testFont(t, "Roboto-Regular.ttf"),
		"DejaVuSans.subset.ttf": testFont(t, "DejaVuSans.subset.ttf"),
	}
	checked := 0
	for scanner := bufio.NewScanner(bytes.NewReader(sums)); scanner.Scan(); {
		line := scanner.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 4 {
			t.Fatalf("malformed reference line %q", line)
		}
		font := fonts[fields[0]]
		if font == nil {
			t.Fatalf("unknown font in reference line %q", line)
		}
		ppem, convErr := strconv.Atoi(fields[1])
		if convErr != nil {
			t.Fatal(convErr)
		}
		sum := sha256.Sum256(dumpOutlines(t, font, float32(ppem), targetNamed(fields[2])))
		if got := hex.EncodeToString(sum[:]); got != fields[3] {
			t.Errorf("%s at %d ppem for %s: outlines differ from FreeType's", fields[0], ppem, fields[2])
		}
		checked++
	}
	if checked == 0 {
		t.Fatal("no reference entries")
	}
}

func TestRefusals(t *testing.T) {
	if _, err := NewFont(func(string) []byte { return nil }); !errors.Is(err, ErrNoOutlines) {
		t.Errorf("expected ErrNoOutlines, got %v", err)
	}
	font := testFont(t, "Roboto-Regular.ttf")
	if _, err := font.NewInstance(7, TargetLCD); !errors.Is(err, ErrHintingDisabled) {
		t.Errorf("expected Roboto to disable its instructions at 7 ppem, got %v", err)
	}
	if _, err := font.NewInstance(0, TargetLCD); err == nil {
		t.Error("expected a size of zero to be refused")
	}
}

// TestDamagedFontsDoNotPanic runs the pipeline over fonts with random bytes of their programs and glyph data
// overwritten: no panic may escape and nothing may loop without bound.
func TestDamagedFontsDoNotPanic(t *testing.T) {
	original := sfntTableMap(t, filepath.Join("..", "..", "testdata", "Roboto-Regular.ttf"))
	rng := rand.New(rand.NewPCG(1, 2))
	rounds := 240
	if testing.Short() {
		rounds = 24
	}
	var o Outline
	fonts, instances, outlines := 0, 0, 0
	for round := range rounds {
		tables := make(map[string][]byte, len(original))
		for tag, data := range original {
			tables[tag] = data
		}
		// Alternate between damaging one table heavily and all of them lightly, so that some fonts still load.
		targets := []string{"fpgm", "prep", "cvt ", "glyf", "loca", "hmtx"}
		heavy := round%2 == 0
		if heavy {
			targets = targets[round/2%len(targets):][:1]
		}
		for _, tag := range targets {
			damaged := bytes.Clone(original[tag])
			count := 1 + rng.IntN(3)
			if heavy {
				count = 1 + len(damaged)/16
			}
			for range count {
				damaged[rng.IntN(len(damaged))] = byte(rng.IntN(256))
			}
			tables[tag] = damaged
		}
		font, err := NewFont(lookup(tables))
		if err != nil {
			continue
		}
		fonts++
		for _, ppem := range []float32{9, 13, 22.5} {
			in, instErr := font.NewInstance(ppem, TargetLCD)
			if instErr != nil {
				continue
			}
			instances++
			for gid := range font.numGlyphs {
				if in.Outline(uint16(gid), &o) {
					outlines++
				}
			}
		}
	}
	if fonts < rounds/2 || instances < rounds/2 || outlines < rounds*100 {
		t.Errorf("the damage kept the pipeline from running: %d fonts, %d instances, %d outlines in %d rounds", fonts,
			instances, outlines, rounds)
	}
}
