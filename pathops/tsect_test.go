// The end-to-end driver for the tSect quad/quad solver. Every intersection the solver reports must be a real touch
// point (the two quads' points at the reported T pair coincide within approximatelyEqual), and the coincident corpus
// must yield at least two coincident entries whose point pairs coincide. Some quad control points below were originally
// float32 literals and are widened through float32 (f32d) to reproduce that precision exactly; the rest are full
// doubles. dq/f32d live in dquad_test.go / dcubiclineintersect_test.go.

package pathops

import "testing"

// quadOneOffTest asserts every reported intersection is a valid touch point.
func quadOneOffTest(t *testing.T, outer, inner int) {
	t.Helper()
	quad1 := quadIntersectTestSet[outer]
	quad2 := quadIntersectTestSet[inner]
	in := newIntersections()
	in.intersectQuadQuad(quad1, quad2)
	for pt := 0; pt < in.usedCount(); pt++ {
		tt1 := in.tVal(0, pt)
		xy1 := quad1.ptAtT(tt1)
		tt2 := in.tVal(1, pt)
		xy2 := quad2.ptAtT(tt2)
		if !xy1.approximatelyEqual(xy2) {
			t.Fatalf("oneOff [%d,%d] pt %d: t1=%g (%g,%g) t2=%g (%g,%g)", outer, inner, pt,
				tt1, xy1.x, xy1.y, tt2, xy2.x, xy2.y)
		}
	}
}

// quadCoincidentTestOne asserts the pair produces a coincident run of at least two entries, each a valid touch point.
func quadCoincidentTestOne(t *testing.T, test1, test2 int) {
	t.Helper()
	quad1 := quadCoincidentTestSet[test1]
	quad2 := quadCoincidentTestSet[test2]
	in := newIntersections()
	in.intersectQuadQuad(quad1, quad2)
	if in.coincidentUsedCount() < 2 {
		t.Fatalf("coincident[%d,%d]: coincidentUsed=%d, want >= 2", test1, test2, in.coincidentUsedCount())
	}
	if in.usedCount() < 2 {
		t.Fatalf("coincident[%d,%d]: used=%d, want >= 2", test1, test2, in.usedCount())
	}
	for pt := 0; pt < in.coincidentUsedCount(); pt += 2 {
		tt1 := in.tVal(0, pt)
		tt2 := in.tVal(1, pt)
		pt1 := quad1.ptAtT(tt1)
		pt2 := quad2.ptAtT(tt2)
		if !pt1.approximatelyEqual(pt2) {
			t.Fatalf("coincident[%d,%d] pt %d: (%g,%g) != (%g,%g)", test1, test2, pt,
				pt1.x, pt1.y, pt2.x, pt2.y)
		}
	}
}

// quadraticStandardTests holds full-order quad pairs with known intersection counts.
var quadraticStandardTests = [][2]dQuad{
	{dq(0, 0, 0, 1, 1, 1), dq(0, 1, 0, 0, 1, 0)}, // one intersection
	{dq(1, 0, 2, 6, 3, 0), dq(0, 1, 6, 2, 0, 3)}, // four intersections
}

func TestPathOpsQuadIntersectionOneOff(t *testing.T) {
	quadOneOffTest(t, 0, 1)
}

func TestPathOpsQuadIntersectionCoincidenceOneOff(t *testing.T) {
	quadCoincidentTestOne(t, 0, 1)
}

func TestPathOpsQuadIntersection(t *testing.T) {
	// oneOffTests: every ordered pair (outer < inner) in the corpus.
	for outer := 0; outer < len(quadIntersectTestSet)-1; outer++ {
		for inner := outer + 1; inner < len(quadIntersectTestSet); inner++ {
			quadOneOffTest(t, outer, inner)
		}
	}
	// coincidentTest: consecutive pairs.
	for i := 0; i+1 < len(quadCoincidentTestSet); i += 2 {
		quadCoincidentTestOne(t, i, i+1)
	}
	// standardTestCases: only when both quads keep full (order-3) form.
	for index, pair := range quadraticStandardTests {
		quad1, quad2 := pair[0], pair[1]
		var reduce1, reduce2 reduceOrder
		if reduce1.reduceQuad(quad1) != 3 || reduce2.reduceQuad(quad2) != 3 {
			continue
		}
		in := newIntersections()
		in.intersectQuadQuad(quad1, quad2)
		for pt := 0; pt < in.usedCount(); pt++ {
			xy1 := quad1.ptAtT(in.tVal(0, pt))
			xy2 := quad2.ptAtT(in.tVal(1, pt))
			if !xy1.approximatelyEqual(xy2) {
				t.Fatalf("standard[%d] pt %d: (%g,%g) != (%g,%g)", index, pt,
					xy1.x, xy1.y, xy2.x, xy2.y)
			}
		}
	}
}

